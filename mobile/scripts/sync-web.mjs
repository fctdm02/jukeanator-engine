// Copies the Web/Mobile UI (src/main/resources/static/app) into mobile/www, the folder Capacitor
// bundles into the native apps, and writes a www/js/config.js that points the bundled UI at the
// JukeANator master server.
//
// The server URL defaults to production. Override it for one run with the environment variable
// JUKEANATOR_API_BASE_URL (absolute URL, no trailing slash), e.g. a test master.
//
// Usage (from the mobile folder): npm run sync-web

import { cpSync, existsSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_API_BASE_URL = 'https://www.jukeanator.com';

const mobileDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = resolve(mobileDir, '..', 'src', 'main', 'resources', 'static', 'app');
const targetDir = join(mobileDir, 'www');

const apiBaseUrl = (process.env.JUKEANATOR_API_BASE_URL || DEFAULT_API_BASE_URL).replace(/\/+$/, '');
if (!/^https?:\/\/[^/]+$/.test(apiBaseUrl)) {
  console.error(`JUKEANATOR_API_BASE_URL must be a scheme and host only (e.g. ${DEFAULT_API_BASE_URL}); got "${apiBaseUrl}"`);
  process.exit(1);
}
if (!existsSync(join(sourceDir, 'index.html'))) {
  console.error(`Web UI not found at ${sourceDir}`);
  process.exit(1);
}

// Start from a clean copy so files deleted from the web UI don't linger in the app bundle.
rmSync(targetDir, { recursive: true, force: true });
cpSync(sourceDir, targetDir, { recursive: true });

writeFileSync(join(targetDir, 'js', 'config.js'),
  '// Generated by mobile/scripts/sync-web.mjs -- do not edit; edit the script or set\n'
  + '// JUKEANATOR_API_BASE_URL instead.\n'
  + `window.JUKEANATOR_CONFIG = {\n  apiBaseUrl: ${JSON.stringify(apiBaseUrl)}\n};\n`);

console.log(`Copied ${sourceDir} to ${targetDir}`);
console.log(`Bundled UI will use server ${apiBaseUrl}`);
